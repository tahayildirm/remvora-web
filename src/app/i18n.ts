@Injectable({ providedIn: 'root' })
export class I18n {
  lang = signal<'en' | 'tr'>(this.savedLanguage());
  private savedLanguage(): 'en' | 'tr' {
    try {
      const saved = window.localStorage.getItem('remvora.language');
      if (saved === 'en' || saved === 'tr') return saved;
    } catch {
      /* Storage may be unavailable in private or restricted browsers. */
    }
    return 'en';
  }
  setLanguage(language: 'en' | 'tr') {
    this.lang.set(language);
    try {
      window.localStorage.setItem('remvora.language', language);
    } catch {
      /* Keep this session usable. */
    }
  }
  t(key: string): string {
    return (
      (this.lang() === 'tr' ? tr[key] : undefined) ?? (en as Record<string, string>)[key] ?? key
    );
  }
}
